export WangLandauResult, wang_landau

struct WangLandauResult{S}
    state::S
    log_density::Vector{Float64}
    histogram::Vector{Int}
    log_modification::Float64
    steps::Int
    converged::Bool
end

"""
    wang_landau(rng, initial; nbins, bin, propose, ...)

Generic Wang–Landau density-of-states sampling. `bin(state)` must return an
integer in `1:nbins`; `propose(rng, state)` must return a separate proposed
state generated by a symmetric proposal kernel, without modifying the current
state. Supply only reachable bins,
with a fixed mapping. Unreachable bins prevent flatness and convergence. The
returned log density is defined only up to an additive constant. `max_steps`
is a hard cap, and `converged` indicates only that the modification-factor
schedule completed, not a proof of statistical accuracy. Check independent
runs and exact small systems before using results scientifically.
"""
function wang_landau(rng::AbstractRNG, initial; nbins::Integer, bin, propose,
                    flatness::Real=0.8, check_interval::Integer=1000,
                    logf_initial::Real=1.0, logf_final::Real=1e-4,
                    reduction::Real=0.5, max_steps::Integer=10_000_000)
    nbins > 0 || throw(ArgumentError("nbins must be positive"))
    0 < flatness <= 1 || throw(ArgumentError("flatness must be in (0,1]"))
    check_interval > 0 && max_steps > 0 || throw(ArgumentError("step counts must be positive"))
    isfinite(logf_initial) && isfinite(logf_final) && 0 < logf_final < logf_initial ||
        throw(ArgumentError("require finite 0 < logf_final < logf_initial"))
    0 < reduction < 1 || throw(ArgumentError("reduction must be in (0,1)"))
    index(s) = begin
        i = bin(s)
        i isa Integer && 1 <= i <= nbins || throw(ArgumentError("bin must return an integer in 1:nbins"))
        Int(i)
    end
    state = deepcopy(initial)
    current = index(state)
    logg = zeros(Float64, nbins)
    hist = zeros(Int, nbins)
    logf = Float64(logf_initial)
    steps = 0
    while steps < max_steps && logf > logf_final
        candidate = propose(rng, state)
        proposed = index(candidate)
        # Proposal is symmetric; the current adaptive target is 1/g(E).
        # Draw explicitly to preserve this algorithm's one-variate-per-step
        # convention, including deterministic acceptance.
        logratio = logg[current] - logg[proposed]
        if metropolis_accept(logratio, rand(rng))
            state = candidate
            current = proposed
        end
        logg[current] += logf
        hist[current] += 1
        steps += 1
        if steps % check_interval == 0 && minimum(hist) >= flatness * (sum(hist) / nbins)
            hist .= 0
            logf *= reduction
        end
    end
    logg .-= minimum(logg)
    return WangLandauResult(state, logg, hist, logf, steps, logf <= logf_final)
end
